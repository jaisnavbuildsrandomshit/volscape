"""Reproducible headless experiment on the bundled SYNTHETIC demo chain.

    python scripts/run_experiment.py

Writes exports/synthetic_demo/ (experiment.json, CSVs, standalone HTML charts) and regenerates
docs/RESULTS_SYNTHETIC.md from the numbers computed in this run.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from volscape import charts as ch  # noqa: E402
from volscape import diagnostics as dg  # noqa: E402
from volscape.export import experiment_record, surface_grid_frame, to_json  # noqa: E402
from volscape.pipeline import run_pipeline  # noqa: E402
from volscape.synthetic import SyntheticSpec  # noqa: E402

SRC = ROOT / "data" / "synthetic_demo.csv"
OUT = ROOT / "exports" / "synthetic_demo"
LABEL = "SYNTHETIC · bundled demo chain (SSVI model, seed 7, 0.15 vol-pt IV noise)"


def f(x, spec="{:.3f}"):
    return "N/A" if x is None or not np.isfinite(x) else spec.format(x)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    res = run_pipeline(SRC.read_bytes(), LABEL, True)
    assert res.ok, res.validation.fatal
    spec = SyntheticSpec(seed=7, iv_noise_volpts=0.15)
    rec = experiment_record(res, "svi", seed=7, synthetic_spec=spec.to_dict())
    (OUT / "experiment.json").write_text(to_json(rec), encoding="utf-8")
    surface_grid_frame(res.svi).to_csv(OUT / "surface_grid_svi.csv", index=False)
    pd.DataFrame([s.to_row() for s in res.fits]).to_csv(OUT / "svi_parameters.csv", index=False)
    res.chain.to_csv(OUT / "accepted_quotes.csv", index=False)
    res.validation.rejected.to_csv(OUT / "rejected_rows.csv", index=False)
    d = {m: res.diagnostics(m) for m in ("svi", "baseline")}
    d["svi"]["per_expiry"].to_csv(OUT / "errors_svi.csv", index=False)
    exp30 = sorted(res.chain.expiry.unique())[2]
    (OUT / "surface_3d.html").write_text(ch.standalone_html(
        ch.surface_figure(res.svi, res.chain, res.obs, highlight_expiry=exp30), "VOLSCAPE · SVI surface (SYNTHETIC)"), encoding="utf-8")
    (OUT / "smile_30d.html").write_text(ch.standalone_html(
        ch.smile_figure(res, exp30), "VOLSCAPE · 30d smile (SYNTHETIC)"), encoding="utf-8")

    h = d["svi"]["headline"]
    par = dg.parity_check(res.chain)
    st = res.chain.iv_mid_status.value_counts().to_dict()
    stb = res.chain.iv_bid_status.value_counts().to_dict()
    rows = "\n".join(
        f"| {s.expiry:%Y-%m-%d} | {s.T * 365:.0f} | {s.status} | {s.n_points} | {f(s.rmse_volpts)} | {f(s.max_abs_err_volpts)} |"
        for s in res.fits)
    cal = d["svi"]["calendar"]
    bf = d["svi"]["butterfly"]
    cc = d["svi"]["call_checks"]
    meth = "\n".join(
        f"| {m.upper()} | {sub} | {f(a['iv_rmse_volpts'])} | {f(a['iv_max_abs_volpts'])} | {f(a['price_rmse'], '{:.4f}')} | {f(a['pct_in_band'], '{:.1f}')} |"
        for m in ("svi", "baseline") for sub, a in (("fit set", d[m]["aggregate"]), ("all quotes", d[m]["aggregate_all"])))
    md = f"""# Observed results — SYNTHETIC experiment

> **SYNTHETIC DATA — NOT MARKET DATA.** Every number below comes from the bundled chain
> `data/synthetic_demo.csv`, generated by `scripts/generate_data.py` from a disclosed SSVI model
> (seed 7, 0.15 vol-pt Gaussian IV noise, stylised bid/ask widths). It shows that the pipeline
> works. It says nothing about any real market.

Regenerate this file with `python scripts/run_experiment.py`; the matching machine-readable
record is `exports/synthetic_demo/experiment.json` (input SHA-256 `{res.validation.meta.input_sha256}`).

## Data and validation
- Rows: {res.validation.n_input} input · {len(res.chain)} accepted · {len(res.validation.rejected)} rejected.
- Mid-IV solver status: {st}. Bid-IV status: {stb}
  (bid INVALID_PRICE = deep-ITM bids below the model-free lower bound, reported and not repaired).
- Low-vega quotes (vega < 0.005 per vol pt) flagged and excluded from fitting: {int(res.chain.low_vega.sum())}.
- Put–call parity: {int(par.within_band.sum())} / {len(par)} pairs consistent within bid/ask bands.

## Headline (SVI surface)
| metric | value |
|---|---|
| 30-day forward-ATM IV | {f(h['atm_iv_30d'] * 100, '{:.2f}')} % |
| 30-day skew σ(k=−0.10) − σ(k=+0.10) | {f(h['skew_30d_volpts'], '{:+.2f}')} vol pts |
| term slope ATM({h['term_slope_T'] * 365:.0f}d) − ATM(30d) | {f(h['term_slope_volpts'], '{:+.2f}')} vol pts |

## SVI calibration per expiry (IV errors in vol points, fit set)
| expiry | days | status | points | RMSE | max abs |
|---|---|---|---|---|---|
{rows}

## Method comparison
| method | subset | IV RMSE (vp) | IV max (vp) | price RMSE | model price in bid/ask (%) |
|---|---|---|---|---|---|
{meth}

The baseline interpolates the fit set exactly, so its fit-set error is ~0 by construction; the
"all quotes" rows (including ITM quotes not used in fitting) are the fair comparison.

## Static-arbitrage diagnostics (finite grids)
- Calendar (101-pt shared k grids, {len(cal)} consecutive pairs): {int(cal.n_violations.fillna(0).sum())} sampled violations.
- SVI butterfly g(k) on 201-pt grids: minimum g = {f(bf.min_g.min(), '{:.4f}')}; negative samples = {int(bf.n_negative.sum())}.
- Model call prices (161-pt strike grids): monotonicity violations = {int(cc.monotonic_violations.sum())},
  convexity violations = {int(cc.convexity_violations.sum())}, minimum density = {f(cc.min_density.min(), '{:.3e}')}.

These checks look only at sampled grid points. They do not prove that no arbitrage exists
between or beyond those points. The generating SSVI parameters satisfy the Gatheral–Jacquier
no-arbitrage conditions, so a clean result here is the expected outcome, not a discovery.
"""
    (ROOT / "docs" / "RESULTS_SYNTHETIC.md").write_text(md, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} and docs/RESULTS_SYNTHETIC.md")


if __name__ == "__main__":
    main()
